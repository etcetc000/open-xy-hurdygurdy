"""Generate periodic, band-limited drone waves from the physical solver.

Requires a host C++ compiler and NumPy. Scratch outputs belong outside this
machine repository. Only drone_waves.h is a machine source asset.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess
import numpy as np

parser=argparse.ArgumentParser()
parser.add_argument('--sdk',type=Path,required=True)
parser.add_argument('--scratch',type=Path,required=True)
parser.add_argument('--cxx',default='clang++')
args=parser.parse_args()
root=Path(__file__).resolve().parents[1]
args.scratch.mkdir(exist_ok=False,parents=True)
hidden={'creationflags':subprocess.CREATE_NO_WINDOW} if hasattr(subprocess,'CREATE_NO_WINDOW') else {}
exe=(args.scratch/'drone_capture.exe').resolve()
p=subprocess.run([args.cxx,'-O2','-std=c++11','-I'+str(args.sdk.resolve()/'sdk/include'),
                  '-I'+str(root),str(root/'generators/drone_capture.cpp'),'-o',str(exe)],
                 capture_output=True,text=True,**hidden)
if p.returncode: raise RuntimeError(p.stderr)
p=subprocess.run([str(exe)],capture_output=True,text=True,check=True,**hidden)
audio=np.fromstring(p.stdout,sep='\n').reshape(12,3,2,4096)
source=(root/'tables.h').read_text()
periods=np.array([int(x) for x in re.findall(r'\d+',re.search(r'hg_bourdon_period\[12\] = \{(.*?)\};',source,re.S)[1])])
waves=[]; steps=[]; report=[]
theta=np.arange(128)*2*np.pi/128
for tonic in range(12):
    for role, divisor in enumerate([1,3,4]):
        period_q12=int(periods[tonic])//4//divisor
        nominal=period_q12/4096
        # Capture remains at 11.025 kHz. Runtime drones use 5.5125 kHz,
        # so phase advances twice as far and only half the harmonics fit.
        steps.append(round(2**32/(nominal/2)))
        for colour in range(2):
            x=audio[tonic,role,colour].copy(); x-=x.mean()
            if np.max(np.abs(x))<32: raise ValueError('Silent physical source')
            center=round(nominal)
            lags=np.arange(max(2,center-3),center+4)
            corr=np.array([np.dot(x[:-lag],x[lag:])/np.sqrt(np.dot(x[:-lag],x[:-lag])*np.dot(x[lag:],x[lag:])) for lag in lags])
            best=int(np.argmax(corr))
            if best==0 or best==len(lags)-1: raise ValueError('Pitch fit at search boundary')
            offset=0.5*(corr[best-1]-corr[best+1])/(corr[best-1]-2*corr[best]+corr[best+1])
            fitted=float(lags[best]+offset)
            harmonics=np.arange(1,min(63,int(nominal/4))+1)
            # Least-squares harmonic fitting at the measured source period.
            angles=2*np.pi*np.arange(len(x))/fitted
            design=np.column_stack([f(angles*k) for k in harmonics for f in [np.cos,np.sin]])
            coefficients=np.linalg.lstsq(design,x,rcond=None)[0]
            complex_coeff=coefficients[0::2]-1j*coefficients[1::2]
            phase=np.angle(complex_coeff[0])
            complex_coeff*=np.exp(-1j*harmonics*phase)
            wave=np.real(np.sum(complex_coeff[:,None]*np.exp(1j*harmonics[:,None]*theta),axis=0))
            # Runtime amplitude tracks the existing bow velocity. The source
            # was captured at Q15 velocity 1064; normalize for a /1024 multiply.
            wave*=1024/1064
            values=np.rint(wave).astype(int)
            if np.max(np.abs(values))>32767: raise ValueError('Wave exceeds Q15')
            waves.append(values.tolist())
            report.append(dict(tonic=tonic,role=role,colour=colour,nominal_period=nominal,
                               source_period=fitted,source_rms=float(np.sqrt(np.mean(x*x))),
                               wave_rms=float(np.sqrt(np.mean(wave*wave))),correlation=float(corr[best])))
lines=['#pragma once','#include "core.h"','namespace hurdygurdy {',
       '// Generated by generators/drone_waves.py; 12 tonics x 3 roles x 2 Rosin endpoints.',
       'const u32 drone_steps[36] = {', '    '+', '.join(str(x)+'u' for x in steps), '};',
       'struct DroneWavePoint { i32 low, high; };',
       'const DroneWavePoint drone_waves[36][129] = {']
for pair in range(36):
    low, high = waves[pair*2:pair*2+2]
    lines.append('    {')
    lines.extend('        {'+str(low[i%128])+', '+str(high[i%128])+'},' for i in range(129))
    lines.append('    },')
lines+=['};','} // namespace hurdygurdy','']
(root/'drone_waves.h').write_text('\n'.join(lines))
(args.scratch/'wave-fit.json').write_text(json.dumps(report,indent=2)+'\n')
print('Generated 72 waveforms; minimum source correlation:',min(r['correlation'] for r in report))
